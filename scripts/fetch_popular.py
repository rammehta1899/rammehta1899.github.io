#!/usr/bin/env python3
"""Regenerate _data/popular.yml from the Google Analytics Data API.

Reads GA4 page views for the last WINDOW_DAYS days, keeps the top blog
post paths, and writes them as YAML the Jekyll homepage renders as the
"Popular essays" section.

Auth: a Google service account (GOOGLE_APPLICATION_CREDENTIALS pointing at
its JSON key). In GitHub Actions this is provided by
google-github-actions/auth from the GA_SERVICE_ACCOUNT_KEY repo secret.

Env:
  GA_PROPERTY_ID  numeric GA4 property id (NOT the G-XXXXXXXXXX
                  measurement id). Required; without it this is a no-op.
  GA_WINDOW_DAYS  lookback window in days (default 90).
  GA_TOP_N        how many posts to store (default 8).
"""
import json
import os
import sys
from datetime import date, timedelta

PROPERTY_ID = os.environ.get("GA_PROPERTY_ID", "").strip()
WINDOW_DAYS = int(os.environ.get("GA_WINDOW_DAYS", "90"))
TOP_N = int(os.environ.get("GA_TOP_N", "8"))
OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "_data", "popular.yml")


def yaml_str(value: str) -> str:
    # JSON string syntax is valid YAML for a scalar.
    return json.dumps(value)


def main() -> int:
    if not PROPERTY_ID:
        print("GA_PROPERTY_ID is not set; leaving _data/popular.yml unchanged.")
        return 0

    from google.analytics.data_v1beta import BetaAnalyticsDataClient
    from google.analytics.data_v1beta.types import (
        DateRange,
        Dimension,
        Metric,
        OrderBy,
        RunReportRequest,
    )

    end = date.today()
    start = end - timedelta(days=WINDOW_DAYS)
    request = RunReportRequest(
        property=f"properties/{PROPERTY_ID}",
        date_ranges=[DateRange(start_date=start.isoformat(), end_date=end.isoformat())],
        dimensions=[Dimension(name="pagePath")],
        metrics=[Metric(name="screenPageViews")],
        order_bys=[
            OrderBy(metric=OrderBy.MetricOrderBy(metric_name="screenPageViews"), desc=True)
        ],
        limit=250,
    )
    response = BetaAnalyticsDataClient().run_report(request)

    posts = []
    for row in response.rows:
        path = row.dimension_values[0].value
        views = int(row.metric_values[0].value)
        # Only real post pages: /blog/YYYY/MM/DD/<slug>/
        if path.startswith("/blog/") and path.count("/") >= 6 and views > 0:
            posts.append((path, views))
        if len(posts) >= TOP_N:
            break

    lines = [
        "# Most-read posts, ranked by Google Analytics page views.",
        "# Regenerated by .github/workflows/update-popular.yml — do not edit by hand.",
        f"generated_at: {yaml_str(end.isoformat())}",
        f"window_days: {WINDOW_DAYS}",
        "posts:",
    ]
    for path, views in posts:
        lines.append(f"  - path: {yaml_str(path)}")
        lines.append(f"    views: {views}")
    if not posts:
        lines.append("  []")

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {len(posts)} popular posts to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
